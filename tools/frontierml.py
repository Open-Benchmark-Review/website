def code(path, lines, text=None):
    """A link to a file and line range in the repository at the reviewed commit."""
    a, _, b = str(lines).partition('-')
    anchor = f'#L{a}' + (f'-L{b}' if b else '')
    shown = path.replace('/', '/<wbr>') + ':' + str(lines)  # long paths may wrap at a slash on phones
    return f'<a href="{GH}{path}{anchor}">{c(shown)}</a>' + (f': {text}' if text else '')


